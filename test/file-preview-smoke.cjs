const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 390, height: 844, webPreferences: { backgroundThrottling: false } });
  await win.loadURL('about:blank');
  await win.webContents.insertCSS(fs.readFileSync(path.join(__dirname, '../src/pwa/file-preview.css'), 'utf8'));
  await win.webContents.executeJavaScript(fs.readFileSync(path.join(__dirname, '../src/pwa/file-preview.js'), 'utf8'));
  const result = await win.webContents.executeJavaScript(`(async () => {
    const wait = async predicate => { for(let i=0;i<100;i++) { if(predicate()) return; await new Promise(r=>setTimeout(r,30)); } throw new Error('Preview did not render'); };
    const row = document.createElement('div'); row.className='file-preview-row'; row.innerHTML='<div class="item-icon">PNG</div>'; document.body.append(row);
    const canvas=document.createElement('canvas'); canvas.width=320; canvas.height=200; const ctx=canvas.getContext('2d'); ctx.fillStyle='#3366ff';ctx.fillRect(0,0,320,200);
    const image=await new Promise(r=>canvas.toBlob(r));
    FilePreview.attach(row.firstChild,{name:'Sample.png',size:image.size},async()=>image);
    await wait(()=>row.querySelector('img')?.naturalWidth>0);
    row.querySelector('button').click();
    await wait(()=>document.querySelector('dialog img')?.naturalWidth>0);
    const fits=document.querySelector('dialog').getBoundingClientRect().width<=innerWidth;
    document.querySelector('dialog button').click();
    await wait(()=>!document.querySelector('dialog'));
    row.innerHTML='<div class="item-icon">TXT</div>';
    FilePreview.attach(row.firstChild,{name:'Notes.txt',size:30},async()=>new Blob(['<script>unsafe()</script>']));
    row.querySelector('button').click();
    await wait(()=>document.querySelector('dialog pre'));
    const literal=document.querySelector('dialog pre').textContent==='<script>unsafe()</script>' && !document.querySelector('dialog script');
    FilePreview.closeAll(); await wait(()=>!document.querySelector('dialog'));
    row.innerHTML='<div class="item-icon">TXT</div>';
    FilePreview.attach(row.firstChild,{name:'Missing.txt',size:30},async()=>{throw new Error('Missing');});
    row.querySelector('button').click();
    await wait(()=>document.querySelector('dialog').textContent.includes('Preview unavailable'));
    FilePreview.closeAll();
    return {fits,literal};
  })()`);
  assert.deepEqual(result, { fits: true, literal: true });
  console.log('Preview smoke passed: thumbnail, enlarged image, phone width, literal text, failure feedback, and close cleanup.');
  win.destroy(); app.quit();
}).catch(error => { console.error(error); app.exit(1); });
